# (GPL-2.0-or-later) and carries that licence.
import re
import sys

def defines(path):
    d = {}
    for line in open(path, encoding='utf-8', errors='replace'):
        m = re.match(r'\s*#define\s+(\w+)\s+(0x[0-9A-Fa-f]+|\d+)\b', line)
        if m:
            d[m.group(1)] = int(m.group(2), 0)
    return d

def val(tok, d):
    tok = tok.strip()
    if re.fullmatch(r'0x[0-9A-Fa-f]+|\d+', tok):
        return int(tok, 0)
    return d.get(tok)

def evalsize(expr):
    expr = expr.strip()
    if not re.fullmatch(r'[0-9\s\*\+\(\)]+', expr):
        return None
    return int(eval(expr))

PROBES = {'PROBE_SPI_RDID': 'P_RDID', 'PROBE_SPI_RDID4': 'P_RDID4', 'PROBE_SPI_REMS': 'P_REMS',
          'PROBE_SPI_RES1': 'P_RES1', 'PROBE_SPI_RES2': 'P_RES2'}
WRITES = {'SPI_CHIP_WRITE256': 'W_PAGE', 'SPI_CHIP_WRITE1': 'W_BYTE', 'SPI_WRITE_AAI': 'W_AAI'}

def main():
    src = open(sys.argv[1], encoding='utf-8', errors='replace').read()
    d = defines(sys.argv[2])
    parts = re.split(r'\n\t\{\s*\n\t\t\.vendor', src)
    out = []
    for p in parts[1:]:
        body = '.vendor' + p
        end = body.find('\n\t},')
        if end > 0:
            body = body[:end]
        g = lambda k: (re.search(r'\.' + k + r'\s*=\s*([^,\n]+)', body) or [None, None])[1]
        if not g('bustype') or 'BUS_SPI' not in g('bustype'):
            continue
        probe = (g('probe') or '').strip()
        write = (g('write') or '').strip()
        if probe not in PROBES or write not in WRITES:
            continue
        vendor = re.search(r'\.vendor\s*=\s*"([^"]*)"', body).group(1)
        name = re.search(r'\.name\s*=\s*"([^"]*)"', body).group(1)
        mfg, model = val(g('manufacture_id'), d), val(g('model_id'), d)
        size, page = val(g('total_size'), d), val(g('page_size'), d)
        if None in (mfg, model, size):
            continue
        fb = re.search(r'\.feature_bits\s*=\s*([^;]*?),\s*\n\s*\.', body, re.S)
        feat = fb.group(1) if fb else ''
        four = 1 if 'FEATURE_4BA' in feat else 0
        volt = re.search(r'\.voltage\s*=\s*\{\s*(\d+)\s*,\s*(\d+)\s*\}', body)
        vmin, vmax = (int(volt.group(1)), int(volt.group(2))) if volt else (0, 0)
        ers = []
        for e in re.finditer(r'\.eraseblocks\s*=\s*\{(.*?)\}\s*,\s*\n\s*\.block_erase\s*=\s*SPI_BLOCK_ERASE_([0-9A-F]{2})\b', body, re.S):
            regs = []
            for r in re.finditer(r'\{\s*([^,{}]+?)\s*,\s*([^,{}]+?)\s*\}', e.group(1)):
                s, n = evalsize(r.group(1)), evalsize(r.group(2))
                if s is None or n is None:
                    regs = None
                    break
                regs.append((s, n))
            if regs and len(regs) <= 4 and len(ers) < 5:
                ers.append((int(e.group(2), 16), regs))
        out.append((vendor, name, mfg, model, size, page or 256, PROBES[probe], WRITES[write], four, vmin, vmax, ers))
    print('/* flashchips_tab.c -- generated by flashchips_gen.py from flashrom 1.4.0 flashchips.c (GPL-2.0-or-later);')
    print(' * do not edit.  %d SPI NOR parts. */' % len(out))
    print('#include "flashchips.h"')
    print('const fc_part_t fc_parts[] = {')
    for (vendor, name, mfg, model, size, page, probe, write, four, vmin, vmax, ers) in out:
        es = ', '.join('{0x%02X, {%s}}' % (op, ', '.join('{%d, %d}' % r for r in regs)) for op, regs in ers)
        print('    {"%s", "%s", 0x%02X, 0x%04X, %d, %d, %s, %s, %d, %d, %d, %d, {%s}},' %
              (vendor, name, mfg & 0xFFFF, model & 0xFFFF, size, page, probe, write, four, vmin, vmax, len(ers), es))
    print('};')
    print('const int fc_nparts = %d;' % len(out))

main()
