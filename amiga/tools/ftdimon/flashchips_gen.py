#   flashchips_gen.py <flashrom flashchips.c> <flashrom include/flashchips.h> > flashchips_tab.c
#
# Taken: entries on BUS_SPI probed by JEDEC ID (PROBE_SPI_RDID, RDID4), REMS (0x90) or RES (0xAB, one or two bytes),
# written by page program (SPI_CHIP_WRITE256), byte program (SPI_CHIP_WRITE1) or SST AAI (SPI_WRITE_AAI).  Per part:
# vendor, name, manufacturer and model ID, size, page size, the probe, the write method, 4-byte addressing, the
# voltage range and up to five erasers, each an opcode and up to four {size, count} regions.  Everything else in the
# entry (lock printing, status register bit maps, test state) is not used.
#
